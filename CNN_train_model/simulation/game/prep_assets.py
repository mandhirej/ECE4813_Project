"""Assets for the host game simulation (gesture_work/sim/game).

  build/cnn_weights.h   integer CNN weights read from the Quartus project files
                        (same files and arithmetic as the bit-exact RTL check)
  build/assets.bin      card sprites (real dataset photos) and hand sprites
                        (real gesture photos), already at camera-snapshot scale
  build/assets_preview.png
"""
import glob
import os
import struct
import sys
import zipfile

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.dirname(HERE)
GW = os.path.dirname(SIM)
PROJECT = os.path.dirname(GW)
sys.path.insert(0, GW)
sys.path.insert(0, SIM)
from train_gesture_head import HW, load_hw_weights  # noqa: E402
from make_vectors import read_mif, fc_from_rom  # noqa: E402

B = os.path.join(HERE, "build")
os.makedirs(B, exist_ok=True)

# configured deck (game_config.h) + both jokers; CNN class ids (game_core.h encoding)
CARDS = {  # folder in the card dataset -> CNN class
    "ADiamonds": 37, "2Diamonds": 5, "3Diamonds": 9, "4Diamonds": 13,
    "8Clubs": 28, "9Clubs": 32, "10Clubs": 0, "JClubs": 40,
    "8Hearts": 30, "9Hearts": 34, "10Hearts": 2, "JHearts": 42,
    "ASpade": 39, "2Spade": 7, "3Spade": 11, "4Spade": 15,
    "JokerB": 44, "JokerR": 45,
}
CARD_W, CARD_H = 52, 78        # portrait card inside a 90x58 landscape cell (rotated)
ZONE_W, ZONE_H = 90, 174       # gesture zone above DRAW


def c_array(name, ctype, arr):
    vals = ",".join(str(int(v)) for v in np.asarray(arr).flatten())
    return f"static const {ctype} {name}[{np.asarray(arr).size}]={{{vals}}};\n"


def export_weights():
    p, w1, b1, w2, b2 = load_hw_weights()
    wfc, bfc = fc_from_rom(read_mif(os.path.join(HW, "weights_linear_gesture.mif")), os.path.join(HW, "linear_bias.vh"))
    with open(os.path.join(B, "cnn_weights.h"), "w") as f:
        f.write("/* generated by prep_assets.py from the Quartus project weight files */\n")
        f.write(f"#define SIM_L1_SHIFT {p['L1_SHIFT']}\n#define SIM_L2_SHIFT {p['L2_SHIFT']}\n")
        f.write(f"#define SIM_FC_CLASSES {wfc.shape[0]}\n")
        f.write(c_array("sim_w1", "int8_t", w1) + c_array("sim_b1", "int32_t", b1))
        f.write(c_array("sim_w2", "int8_t", w2) + c_array("sim_b2", "int32_t", b2))
        f.write(c_array("sim_wfc", "int8_t", wfc) + c_array("sim_bfc", "int32_t", bfc))
    print("weights:", wfc.shape[0], "FC classes")


def card_sprite(jpg_bytes):
    img = cv2.imdecode(np.frombuffer(jpg_bytes, np.uint8), cv2.IMREAD_COLOR)
    gray = ((img[..., 2].astype(np.uint16) >> 2) + (img[..., 1] >> 1) + (img[..., 0] >> 2)).astype(np.uint8)
    ys, xs = np.where(gray > 90)
    crop = img[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    if crop.shape[1] > crop.shape[0]:          # make it portrait
        crop = np.rot90(crop)
    port = cv2.resize(crop, (CARD_W, CARD_H), interpolation=cv2.INTER_AREA)
    # On the board the card lies landscape with its TOP pointing LEFT (BOARD_LANDSCAPE_ROTATION 1)
    land = np.ascontiguousarray(np.rot90(port, 1))
    return land[..., ::-1]                     # RGB


def hand_sprites():
    """RGBA hands at zone size, wrist at the bottom (arm from the DRAW side)."""
    sys.path.insert(0, GW)
    from prep_gesture_dataset import load, skin_mask, hand_window
    out = []
    for gid, folder in enumerate(["Fist_dataset", "Open_palm_dataset", "Peace_dataset"]):
        src = [d for d in glob.glob(os.path.join(PROJECT, "gesture_raw", "*", "*")) if os.path.basename(d).strip() == folder][0]
        files = sorted(glob.glob(os.path.join(src, "*.jpg")))
        for f in files[-6:]:                     # test-session photos, not in the training split
            bgr = load(f)
            m = skin_mask(bgr)
            if m is None:
                continue
            x0, y0, ww, wh = hand_window(m)
            M = np.float32([[ww / ZONE_W, 0, x0], [0, wh / ZONE_H, y0]])
            flags = cv2.INTER_AREA | cv2.WARP_INVERSE_MAP
            rgb = cv2.warpAffine(bgr, M, (ZONE_W, ZONE_H), flags=flags, borderMode=cv2.BORDER_REFLECT)[..., ::-1]
            a = cv2.warpAffine(m, M, (ZONE_W, ZONE_H), flags=cv2.INTER_LINEAR | cv2.WARP_INVERSE_MAP)
            rgba = np.dstack([rgb, a])[::-1, ::-1]          # wrist at the bottom
            out.append((gid, np.ascontiguousarray(rgba)))
    return out


def main():
    export_weights()
    z = zipfile.ZipFile(os.path.join(PROJECT, "swee's dataset-20261021T083221Z-1-004.zip"))
    names = z.namelist()
    sprites = []
    for folder, cls in CARDS.items():
        cand = sorted(n for n in names if f"/val/{folder}/" in n and n.lower().endswith((".jpg", ".png")) and "blackfoam" in n)
        cand = cand or sorted(n for n in names if f"/{folder}/" in n and "blackfoam" in n)
        sprites.append((cls, card_sprite(z.read(cand[0]))))
    hands = hand_sprites()
    with open(os.path.join(B, "assets.bin"), "wb") as f:
        f.write(struct.pack("<II", len(sprites), len(hands)))
        for cls, im in sprites:
            f.write(struct.pack("<iii", cls, im.shape[1], im.shape[0]) + im.astype(np.uint8).tobytes())
        for gid, im in hands:
            f.write(struct.pack("<iii", gid, im.shape[1], im.shape[0]) + im.astype(np.uint8).tobytes())
    # preview
    tiles = [np.pad(im, ((2, 2), (2, 2), (0, 0)), constant_values=255) for _, im in sprites]
    row = np.hstack([cv2.resize(t, (82, 56)) for t in tiles])
    hrow = np.hstack([np.pad(im[..., :3] * (im[..., 3:] / 255.0), ((2, 2), (2, 2), (0, 0)), constant_values=255).astype(np.uint8) for _, im in hands])
    w = max(row.shape[1], hrow.shape[1])
    sheet = np.full((row.shape[0] + hrow.shape[0] + 4, w, 3), 255, np.uint8)
    sheet[:row.shape[0], :row.shape[1]] = row
    sheet[row.shape[0] + 4:, :hrow.shape[1]] = hrow
    cv2.imwrite(os.path.join(B, "assets_preview.png"), cv2.resize(sheet[..., ::-1], None, fx=1.5, fy=1.5, interpolation=cv2.INTER_NEAREST))
    print(f"{len(sprites)} card sprites, {len(hands)} hand sprites")


if __name__ == "__main__":
    main()
